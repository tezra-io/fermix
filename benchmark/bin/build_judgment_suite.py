r"""Build the open-loop judgment candidate suite from the owner's labels (M83 §06).

  uv run bin/build_judgment_suite.py --labels <labels.json>

Reads the invented moments (suites/capability/fixtures/judgment_moments.json, the
labelling page's own set) and the owner's labels as the page's data tool returns them,
a JSON list of {"id": "s01", "data": {"label": "let_go"|"when_around"|"check_in",
"note": "..."}}, and writes suites/capability/candidates/open_loop_judgment.yaml: one
capability task per labelled moment, graded from memory.db by
checkers/open_loop_judgment.py.

An unlabelled moment (absent from the export, or with no label) is skipped and named.
A label for a moment the set does not hold, a moment labelled twice and a label
outside the three answers are input errors: nothing is written. The owner's notes are
counted, never copied into the suite. The suite is validated by the same loader the
runners use before it is written, so a bad build never lands.

Exit 0: written. Exit 2: an input error or no labelled moment; nothing written.

STAGE 0: THE RED BASELINE ON THE ENGINE BEFORE M83 (§06, §16). The design records, moment
by moment, which labels today's engine misses before any M83 engine change lands. The
M83 bin/seed_state.exs cannot run there: its reset deletes every recorded reply through
Repo.list_open_loop_reactions/2, which that engine does not have. So stage 0 runs that
engine's own helper rather than a second path in this one:

  1. Check out the engine before M83: the dev commit M83 was rebased onto, 87d45f26
     (any dev commit before M83 lands reads the same).
  2. Copy these M83 files into it, at the same paths under benchmark/:
       bin/build_judgment_suite.py
       bin/judgment_agreement.py
       suites/capability/fixtures/judgment_moments.json
       suites/capability/fixtures/state/open_loop_judgment_reset.json
       suites/capability/checkers/open_loop_judgment.py
       bin/run_capability.py and bin/evallib/aggregate.py, which write the per-trial
         records (`trial_records` in results.json) judgment_agreement.py reads; the
         older pair writes none, and the agreement script refuses such a run.
     Do NOT copy bin/seed_state.exs: keep that checkout's own. Its reset closes every
     live open loop and touches no reactions table, and it reads the reset spec
     {"open_loops": []} as nothing to seed (`Map.get(spec, "open_loops", [])` reaches
     the empty clause of seed_open_loops!/3), then prints the `now` and `today` the
     checker reads.
  3. In that checkout's benchmark/:
       uv run bin/build_judgment_suite.py --labels <labels.json>
       bin/capability-daemon.sh up
       uv run bin/run_capability.py --candidates --suite cap_open_loop_judgment \
         --trials 3 --confirm-daemon-isolated --confirm-isolated-env
       bin/capability-daemon.sh down
  4. The checker finds no `reach` column (migration 51 has not run there), so it grades
     keep against let go only and writes `stage=0` in every detail; read the run with
     `uv run bin/judgment_agreement.py <run>/results.json`. Keep that results.json:
     the stage 1 run pairs against it with `--baseline`, on keep or let go for both.
"""
from __future__ import annotations

import argparse
import json
import os
import shutil
import sys
import tempfile

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
SKILL_DIR = os.path.dirname(HERE)
sys.path.insert(0, HERE)

from evallib import suites  # noqa: E402

LABELS = ("let_go", "when_around", "check_in")
SUITE_NAME = "cap_open_loop_judgment"
MOMENTS_PATH = os.path.join(SKILL_DIR, "suites", "capability", "fixtures",
                            "judgment_moments.json")
OUT_PATH = os.path.join(SKILL_DIR, "suites", "capability", "candidates",
                        "open_loop_judgment.yaml")
CHECKER = "suites/capability/checkers/open_loop_judgment.py"
RESET_STATE = "suites/capability/fixtures/state/open_loop_judgment_reset.json"
CHECKER_TIMEOUT_MS = 60000
TITLE_MAX = 90

HEADER = """\
# GENERATED by bin/build_judgment_suite.py from the owner's labels: rebuild, never
# hand-edit. MILESTONE_83 §06.
#
# WHAT IT MEASURES. One task per moment the owner labelled on the private labelling
# page (Follow-up Judgments), each an invented message the owner might send in their
# own private chat. The turn drives that message through the real agent path, and the
# checker reads memory.db for what Fermix kept live: let_go = no new live loop,
# when_around = one with reach conversation, check_in = one with reach message. The
# label is in each task's checker.expect and its tag (label_<answer>), so
# `--tag label_check_in` runs one answer's moments. bin/judgment_agreement.py reads a
# run's results.json and prints agreement per label, Cohen's kappa, the confusion
# table, a Wilson interval on the per-moment agreement (none per trial: the trials of
# one moment are not independent) and the costliest error (check in where the owner
# said let it go) on its own line, and counts apart the trials in which code refused
# the note, so a code limit is not read as a judgment miss.
#
# TRIALS. Three per moment, the capability runner's default (`--trials 3`; trials are a
# run flag, not a suite key): one stochastic trial reads sampling noise as drift. The
# agreement script takes the majority of each moment's trials.
#
# RESET. `checker.state` points every task at an empty spec, so bin/seed_state.exs runs
# before every trial: it closes every live open loop, removes every scheduled job and
# cancels every active reminder. Each trial starts with no live loop, no cleanup turn
# depends on the model, and the home never reaches its twenty live loops. Every loop
# created after the seed is the trial's own.
#
# MULTI-MESSAGE MOMENTS. A moment of two messages is two turns in one session, as the
# owner sent them; the checker grades the state after the last.
#
# DATES. Each moment keeps its relative phrasing ("Monday", "tomorrow at 2pm", "the
# 18th") exactly as the owner read it: resolving it is part of the judgment under test,
# and the run's own date decides what it resolves to. So no gate reads a date: the
# checker grades only whether a loop was kept and its reach, and reports the anchor kind
# and horizon class for reading a miss, never as a score. The time each moment showed on
# the page is kept as `labelled_when` for the same reading and is never sent; the
# daemon's clock is the run's. A dated moment that lands within two days of its date is
# imminent, and the routing line then also stores a reminder, so no task gates on
# event_store; the reset cancels it before the next trial.
#
# READ WITH THE DATE. These moments name a time whose distance from the run moves with
# the run's date, weekday or hour, so a miss on one is read against the run's date
# before it is read as judgment: a weekday, s01 s02 s10 s11 s17 s20 s24 s31 s33 s38
# s40; a day of the month or a month, s06 s25 s32 s35 s42 s51 s56; a part of today or
# tomorrow, s08 s22 s53.
#
# SAFETY. Every task bans schedule_job: no moment asks for a scheduled job, and one would
# message the owner about a personal moment outside the open-loop consent limits. The
# costliest error is a graded outcome and stays out of the safety column.
#
# STAGE 0. On a database without the `reach` column (before migration 51) the checker
# grades keep against let go only and marks its detail `stage=0`; the agreement script
# reads such a run that way. The pre-M83 baseline runs on that engine's own
# bin/seed_state.exs: the recipe is in bin/build_judgment_suite.py's docstring.
#
# PRECONDITIONS. `[fermix_core.open_loops] enabled = true` (pre-granted by
# bin/seed_capability_home.py) and a chat-capable owner inbox, or open_loop_note refuses
# with no_target. Parked under candidates/ until three runs on an unchanged prompt have
# measured the noise floor; run it with `--candidates --suite cap_open_loop_judgment`.
"""


class BuildError(ValueError):
    pass


def load_moments(path: str) -> list[dict]:
    with open(path, encoding="utf-8") as fh:
        moments = json.load(fh)
    if not isinstance(moments, list) or not moments:
        raise BuildError(f"{path}: the moments must be a non-empty JSON list")
    seen = set()
    for moment in moments:
        ok = (isinstance(moment, dict) and isinstance(moment.get("id"), str)
              and isinstance(moment.get("when"), str)
              and isinstance(moment.get("messages"), list) and moment["messages"]
              and all(isinstance(m, str) and m.strip() for m in moment["messages"]))
        if not ok:
            raise BuildError(f"{path}: malformed moment {moment!r}")
        if moment["id"] in seen:
            raise BuildError(f"{path}: moment {moment['id']} appears twice")
        seen.add(moment["id"])
    return moments


def load_labels(path: str, moment_ids: set[str]) -> dict[str, dict]:
    """id -> {"label", "note"} for every labelled moment; unlabelled ones are absent."""
    with open(path, encoding="utf-8") as fh:
        export = json.load(fh)
    if not isinstance(export, list):
        raise BuildError(f"{path}: the labels export must be a JSON list of "
                         '{"id": ..., "data": {"label": ..., "note": ...}}')
    labels: dict[str, dict] = {}
    seen: set[str] = set()
    for entry in export:
        moment_id, data = _entry(entry, path)
        if moment_id not in moment_ids:
            raise BuildError(f"{path}: a label for {moment_id!r}, which the moment set "
                             "does not hold")
        if moment_id in seen:
            raise BuildError(f"{path}: moment {moment_id} is labelled twice")
        seen.add(moment_id)
        label = data.get("label")
        if label in (None, ""):
            continue
        if label not in LABELS:
            raise BuildError(f"{path}: moment {moment_id} has label {label!r}, not one of "
                             f"{LABELS}")
        labels[moment_id] = {"label": label, "note": str(data.get("note") or "").strip()}
    return labels


def _entry(entry, path: str) -> tuple[str, dict]:
    if not (isinstance(entry, dict) and isinstance(entry.get("id"), str)
            and isinstance(entry.get("data"), dict)):
        raise BuildError(f"{path}: malformed label entry {entry!r}")
    return entry["id"], entry["data"]


def task(moment: dict, label: str) -> dict:
    """One scenario holding one capability task: each moment is its own world."""
    messages = moment["messages"]
    title = f"{moment['when']}: {' / '.join(messages)}"
    if len(title) > TITLE_MAX:
        title = title[:TITLE_MAX - 1].rstrip() + "…"
    case: dict = {"id": moment["id"]}
    if len(messages) == 1:
        case["query"] = messages[0]
    else:
        case["turns"] = [{"query": message} for message in messages]
    case["expect"] = {"tools_none": ["schedule_job"]}
    case["checker"] = {
        "script": CHECKER,
        "mode": "json",
        "state": RESET_STATE,
        "timeout_ms": CHECKER_TIMEOUT_MS,
        "expect": {"label": label, "moment": moment["id"],
                   "labelled_when": moment["when"]},
    }
    return {"id": moment["id"], "title": title, "severity": "normal",
            "tags": ["capability", "open_loops", "judgment", f"label_{label}"],
            "cases": [case]}


def suite_document(moments: list[dict], labels: dict[str, dict]) -> dict:
    return {
        "suite": SUITE_NAME,
        "risk": "isolated_mutation",
        "title": "Capability — open-loop judgment against the owner's labels (memory.db)",
        "description": (
            "Each labelled moment runs through the real agent path and the checker reads "
            "what Fermix kept: no loop, a loop raised only in conversation, or one that "
            "may message. Agreement with the owner's label is the measure; "
            "bin/judgment_agreement.py reports it."),
        "defaults": {"judge": False, "timeout_ms": 180000},
        "scenarios": [task(m, labels[m["id"]]["label"]) for m in moments
                      if m["id"] in labels],
    }


def render(document: dict) -> str:
    body = yaml.safe_dump(document, sort_keys=False, allow_unicode=True, width=1000,
                          default_flow_style=False)
    return HEADER + body


def validate(text: str) -> None:
    """Load the built suite with the runners' own loader before it is written."""
    with tempfile.TemporaryDirectory(prefix="judgment-suite-") as tmp:
        with open(os.path.join(tmp, "open_loop_judgment.yaml"), "w", encoding="utf-8") as fh:
            fh.write(text)
        try:
            suites.load_all(tmp)
        except suites.SuiteError as exc:
            raise BuildError("the built suite does not validate:\n  - "
                             + "\n  - ".join(exc.problems)) from exc


def summary(moments: list[dict], labels: dict[str, dict]) -> list[str]:
    counts = {label: sum(1 for v in labels.values() if v["label"] == label)
              for label in LABELS}
    unlabelled = [m["id"] for m in moments if m["id"] not in labels]
    notes = sum(1 for v in labels.values() if v["note"])
    lines = [f"labelled {len(labels)} of {len(moments)}: "
             + ", ".join(f"{label} {counts[label]}" for label in LABELS)]
    if unlabelled:
        lines.append(f"skipped {len(unlabelled)} unlabelled: {', '.join(unlabelled)}")
    lines.append(f"{notes} note(s) left out of the suite (they stay on the page)")
    return lines


def build(moments_path: str, labels_path: str, out_path: str) -> list[str]:
    moments = load_moments(moments_path)
    labels = load_labels(labels_path, {m["id"] for m in moments})
    if not labels:
        raise BuildError(f"{labels_path}: no moment is labelled; nothing written")
    text = render(suite_document(moments, labels))
    validate(text)
    tmp_out = out_path + ".tmp"
    with open(tmp_out, "w", encoding="utf-8") as fh:
        fh.write(text)
    shutil.move(tmp_out, out_path)
    return [*summary(moments, labels), f"wrote {out_path}"]


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--labels", required=True, help="the labels export (JSON list)")
    parser.add_argument("--moments", default=MOMENTS_PATH, help="the moment set (JSON)")
    parser.add_argument("--out", default=OUT_PATH, help="the suite to write")
    args = parser.parse_args(argv)
    try:
        lines = build(args.moments, args.labels, args.out)
    except (BuildError, OSError, ValueError) as exc:
        print(f"build_judgment_suite: {exc}", file=sys.stderr)
        return 2
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
